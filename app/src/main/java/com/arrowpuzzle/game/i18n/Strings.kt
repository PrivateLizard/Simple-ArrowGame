package com.arrowpuzzle.game.i18n

import androidx.compose.runtime.staticCompositionLocalOf
import java.text.NumberFormat
import java.util.Locale

/**
 * App languages. [code] is the ISO code stored in settings; SYSTEM ("" = follow
 * the device language) is not a real translation table.
 */
enum class AppLanguage(val code: String, val displayName: String) {
    SYSTEM("", "Automatic"),
    ENGLISH("en", "English"),
    GERMAN("de", "Deutsch"),
    FRENCH("fr", "Français"),
    SPANISH("es", "Español"),
    ITALIAN("it", "Italiano"),
    PORTUGUESE("pt", "Português"),
    RUSSIAN("ru", "Русский"),
    CHINESE("zh", "中文"),
    JAPANESE("ja", "日本語"),
    ;

    companion object {
        /** Languages that actually have a translation table. */
        val translated: List<AppLanguage>
            get() = entries.filter { it != SYSTEM }
    }
}

/**
 * Resolves the effective language. A non-empty stored code wins; otherwise the
 * device language is used, falling back to English when unsupported.
 */
fun resolveLanguage(storedCode: String): AppLanguage {
    if (storedCode.isNotBlank()) {
        AppLanguage.entries.firstOrNull { it.code == storedCode }?.let { return it }
    }
    val device = Locale.getDefault().language
    return AppLanguage.entries.firstOrNull { it.code == device } ?: AppLanguage.ENGLISH
}

/**
 * Tiny lookup with English fallback. English is the complete reference table;
 * other languages override as many keys as they provide.
 */
class AppStrings(val language: AppLanguage) {
    private val table: Map<String, String> = TABLES[language] ?: EN

    /** Locale of the app language, used for number formatting. */
    val locale: Locale =
        if (language == AppLanguage.SYSTEM) Locale.ENGLISH else Locale.forLanguageTag(language.code)

    // Only used from the UI thread; NumberFormat is not thread-safe.
    private val integerFormat: NumberFormat = NumberFormat.getIntegerInstance(locale)

    /**
     * Whole number with the grouping separator of the app language,
     * e.g. 3,195 in English, 3.195 in German, 3 195 in French.
     */
    fun number(value: Int): String = integerFormat.format(value.toLong())

    fun t(key: String): String = table[key] ?: EN[key] ?: key

    fun f(key: String, vararg args: Any): String =
        String.format(Locale.US, t(key), *args)
}

val LocalStrings = staticCompositionLocalOf { AppStrings(AppLanguage.ENGLISH) }

/** For tests: the English reference table and all translation tables. */
internal val referenceStrings: Map<String, String> get() = EN
internal val translationTables: Map<AppLanguage, Map<String, String>> get() = TABLES

